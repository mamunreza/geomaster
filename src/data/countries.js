export const getCountriesByRegion = (region) => {
  if (region === REGIONS.ALL) return countries;
  return countries.filter((c) => c.region === region);
};

export const shuffle = (arr) => {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
};

export const generateQuizQuestions = (region, count, type) => {
  const pool = getCountriesByRegion(region);
  const selected = shuffle(pool).slice(0, Math.min(count, pool.length));
  return selected.map((correct) => {
    const distractors = shuffle(pool.filter((c) => c.id !== correct.id)).slice(0, 3);
    const options = shuffle([correct, ...distractors]);
    return { correct, options, type };
  });
};
